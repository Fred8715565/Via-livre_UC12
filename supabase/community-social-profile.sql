-- Bucket público apenas para imagens da comunidade; escrita restrita à pasta do próprio usuário.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('community-photos', 'community-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Fotos da comunidade são públicas para leitura" on storage.objects;
create policy "Fotos da comunidade são públicas para leitura" on storage.objects
  for select using (bucket_id = 'community-photos');
drop policy if exists "Usuário envia foto na própria pasta" on storage.objects;
create policy "Usuário envia foto na própria pasta" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'community-photos' and (storage.foldername(name))[1] = auth.uid()::text
  );
drop policy if exists "Usuário apaga foto da própria pasta" on storage.objects;
create policy "Usuário apaga foto da própria pasta" on storage.objects
  for delete to authenticated using (
    bucket_id = 'community-photos' and (storage.foldername(name))[1] = auth.uid()::text
  );

