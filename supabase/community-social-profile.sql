-- Perfil privado: o CPF nunca é incluído em consultas públicas da comunidade.
create table if not exists public.user_private_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  cpf text null check (cpf is null or cpf ~ '^[0-9. -]{11,14}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.user_private_profiles enable row level security;
drop policy if exists "Usuário vê seu perfil privado" on public.user_private_profiles;
create policy "Usuário vê seu perfil privado" on public.user_private_profiles
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Usuário cria seu perfil privado" on public.user_private_profiles;
create policy "Usuário cria seu perfil privado" on public.user_private_profiles
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Usuário atualiza seu perfil privado" on public.user_private_profiles;
create policy "Usuário atualiza seu perfil privado" on public.user_private_profiles
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Migração segura da tabela de publicações existente.
alter table public.community_posts add column if not exists photo_url text;
alter table public.community_posts add column if not exists is_official boolean not null default false;
drop policy if exists "Usuário publica em seu nome" on public.community_posts;
create policy "Usuário publica em seu nome" on public.community_posts for insert to authenticated
  with check (auth.uid() = user_id and (not is_official or auth.jwt() -> 'app_metadata' ->> 'role' = 'admin'));
alter table public.community_posts alter column message type text;

-- Comentários/respostas.
create table if not exists public.community_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 80),
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);
alter table public.community_comments enable row level security;
drop policy if exists "Comentários visíveis para autenticados" on public.community_comments;
create policy "Comentários visíveis para autenticados" on public.community_comments
  for select to authenticated using (true);
drop policy if exists "Usuário responde em seu nome" on public.community_comments;
create policy "Usuário responde em seu nome" on public.community_comments
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Usuário apaga sua resposta" on public.community_comments;
create policy "Usuário apaga sua resposta" on public.community_comments
  for delete to authenticated using (auth.uid() = user_id);

