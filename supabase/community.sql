-- Execute no SQL Editor do Supabase para habilitar conversas compartilhadas.
create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  place_id text not null,
  author_name text not null check (char_length(author_name) between 1 and 80),
  message text not null check (char_length(message) between 3 and 700),
  created_at timestamptz not null default now()
);
alter table public.community_posts enable row level security;
drop policy if exists "Posts visíveis para usuários autenticados" on public.community_posts;
create policy "Posts visíveis para usuários autenticados" on public.community_posts for select to authenticated using (true);
drop policy if exists "Usuário publica em seu nome" on public.community_posts;
create policy "Usuário publica em seu nome" on public.community_posts for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Usuário apaga sua publicação" on public.community_posts;
create policy "Usuário apaga sua publicação" on public.community_posts for delete to authenticated using (auth.uid() = user_id);
